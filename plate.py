from cadquery import Workplane as cf

plate = cf("XY").box(80, 50, 10)
hole = cf("XY").cylinder(10, 10).translate((20, 0, 0))

part = plate.cut(hole)

print(part.val().isValid(), round(part.val().Volume(), 1))
part.val().exportStl("plate.stl")